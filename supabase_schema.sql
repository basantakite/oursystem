-- १. SYSTEM SETTINGS TABLE (कन्फिगरेसन, नयाँ दलहरू, जातजाति नियम, र टेनेन्ट सेटिङ)
CREATE TABLE IF NOT EXISTS public.system_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT UNIQUE NOT NULL,
    value JSONB,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- २. USERS TABLE (सुपर एडमिन, पालिका एडमिन, वडा संयोजक र फिल्ड कार्यकर्ताहरू)
CREATE TABLE IF NOT EXISTS public.users (
    user_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'Field Worker',
    pin TEXT DEFAULT '1234',
    ward TEXT DEFAULT 'All',
    tole TEXT DEFAULT '',
    active BOOLEAN DEFAULT TRUE,
    access_token TEXT,
    notes JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ३. VOTERS TABLE (हेलम्बु पालिकाका सम्पूर्ण मतदाता नामावली र चुनावी विश्लेषण)
CREATE TABLE IF NOT EXISTS public.voters (
    voter_id TEXT PRIMARY KEY,
    full_name TEXT NOT NULL,
    phone TEXT DEFAULT '',
    ward_no INTEGER DEFAULT 1,
    tole TEXT DEFAULT '',
    booth_no TEXT DEFAULT '',
    serial_no TEXT DEFAULT '',
    age INTEGER,
    gender TEXT DEFAULT 'Other',
    age_group TEXT DEFAULT '',
    dob DATE,
    party_leaning TEXT DEFAULT 'Undecided',
    sentiment TEXT DEFAULT 'swing',
    support_level TEXT DEFAULT 'Neutral',
    influence_level TEXT DEFAULT 'Normal',
    facebook_url TEXT DEFAULT '',
    tiktok_url TEXT DEFAULT '',
    address TEXT DEFAULT '',
    voted_status BOOLEAN DEFAULT FALSE,
    voted_time TIMESTAMPTZ,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    notes JSONB DEFAULT '{}'::jsonb
);

-- ============================================================================
-- ४. HIGH-PERFORMANCE INDEXES (हजारौं मतदाताको विवरण तुरुन्तै खोज्नका लागि)
-- ============================================================================
CREATE INDEX IF NOT EXISTS idx_voters_ward_no ON public.voters(ward_no);
CREATE INDEX IF NOT EXISTS idx_voters_phone ON public.voters(phone);
CREATE INDEX IF NOT EXISTS idx_voters_party_leaning ON public.voters(party_leaning);
CREATE INDEX IF NOT EXISTS idx_voters_sentiment ON public.voters(sentiment);
CREATE INDEX IF NOT EXISTS idx_voters_tole ON public.voters(tole);
CREATE INDEX IF NOT EXISTS idx_voters_full_name ON public.voters(full_name);
CREATE INDEX IF NOT EXISTS idx_users_phone ON public.users(phone);
CREATE INDEX IF NOT EXISTS idx_system_settings_key ON public.system_settings(key);

-- ============================================================================
-- ५. REALTIME BROADCAST ENABLEMENT (वार-रूममा लाइभ परिवर्तन देखिनका लागि)
-- ============================================================================
ALTER TABLE public.voters REPLICA IDENTITY FULL;
ALTER TABLE public.users REPLICA IDENTITY FULL;
ALTER TABLE public.system_settings REPLICA IDENTITY FULL;

-- Supabase Realtime Publication मा टेबलहरू जोड्ने
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'voters'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.voters;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'users'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.users;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'system_settings'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.system_settings;
    END IF;
END $$;

-- ============================================================================
-- ६. ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================================
ALTER TABLE public.voters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.system_settings ENABLE ROW LEVEL SECURITY;

-- Voters Security Policies (एपको लागि सुरक्षित पहुँच)
DROP POLICY IF EXISTS "Allow anon and auth read voters" ON public.voters;
CREATE POLICY "Allow anon and auth read voters" ON public.voters
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow anon and auth insert voters" ON public.voters;
CREATE POLICY "Allow anon and auth insert voters" ON public.voters
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon and auth update voters" ON public.voters;
CREATE POLICY "Allow anon and auth update voters" ON public.voters
    FOR UPDATE USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon and auth delete voters" ON public.voters;
CREATE POLICY "Allow anon and auth delete voters" ON public.voters
    FOR DELETE USING (true);

-- Users Security Policies
DROP POLICY IF EXISTS "Allow anon and auth access users" ON public.users;
CREATE POLICY "Allow anon and auth access users" ON public.users
    FOR ALL USING (true) WITH CHECK (true);

-- System Settings Security Policies
DROP POLICY IF EXISTS "Allow anon and auth access system_settings" ON public.system_settings;
CREATE POLICY "Allow anon and auth access system_settings" ON public.system_settings
    FOR ALL USING (true) WITH CHECK (true);

